def reproducibility_markdown(families):
    lines = [
        "## 切片复现：同一模型的各次运行切片是否相同", "",
        "每个模型当晚提速对照的全部 run（基线、计时版、候选和两种复核，两台机器、各构建；回归、重试和补覆盖的运行不在这张表里）对最早的一次："
        "导出件规范化后是否逐行相同，聚合签名是否相同，保存工程设置是否相同。"
        "聚合签名相同时，路径、进给和挤出量按「类型段 × 层」合计都一样，只是输出顺序或切分不同；不同就是切片结果不同。", "",
        "| 模型（最早一次） | run 数 | 聚合签名相同 | 逐行相同 | 与最早一次聚合签名不同的 run |", "|---|---:|---:|---:|---|",
    ]
    only_infill, same_build_pairs = True, []
    for family in families:
        odd = [row for row in family["runs"] if "signature" in row and not row["signature"]["same"]]
        text = []
        for row in odd:
            g, first = row["signature"], family["runs"][0]
            only_infill = only_infill and g["types_whose_move_count_changed"] == ["Internal solid infill"]
            text.append("`%s`（%s，%s，%s，%s 起；挤出移动 %d 对 %d，内部实心填充 %d 对 %d 段，%d 个「类型段 × 层」格耗料不同；设置不同 %d 键）" % (
                short(row["run_id"]), row["label"], MACHINE_TEXT[row["machine"]], commit_text(row["commit"]), row["started"],
                g["extruding_moves"][0], g["extruding_moves"][1], first["internal_solid_infill_moves"],
                row["internal_solid_infill_moves"], g["filament_by_type_layer"]["differing"], len(row["saved_settings_differing_keys"])))
        lines.append("| %s（`%s`） | %d | %d | %d | %s |" % (
            family["model"], short(family["reference_run"]), family["runs_total"], family["runs_same_as_reference"],
            family["runs_identical_line_by_line"], "；".join(text) or "无"))
        # the runs that differ although build and machine are the same as a run that does not
        for row in odd:
            sibling = next((other for other in family["runs"][1:] if other is not row and other.get("signature", {}).get("same")
                            and (other["machine"], other["commit"]) == (row["machine"], row["commit"])), None)
            if sibling:
                same_build_pairs.append("`%s`（同机同构建的 `%s` 与最早一次相同）" % (short(row["run_id"]), short(sibling["run_id"])))
    lines.append("")
    if any(row.get("signature") and not row["signature"]["same"] for family in families for row in family["runs"]):
        lines += ["不同的几次" + ("都只差在内部实心填充（Internal solid infill），其余类型段的移动数相同" if only_infill
                              else "不止差在内部实心填充") + "。原因今晚没有查；它不是构建或机器造成的："
                  + ("这些 run 的同机同构建里也有与最早一次签名相同的 run：%s" % "；".join(same_build_pairs) if same_build_pairs else "见上表")
                  + "。在这几个模型上拿一次导出件当「基线 G-code」逐行比，要先把这一项算进去。逐 run 的数字见 `stage-timings.json` 的 `reproducibility`。", ""]
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--evidence", default=str(EVIDENCE))
    args = parser.parse_args(argv)
    evidence = Path(args.evidence)
    ledger, receipts = load_ledger(evidence / "ledger.jsonl"), load_receipts(evidence)
    groups = build_stage(ledger, receipts)
    data = dict(ledger_facts(ledger))
    data.update({
        "schema": "ninehour_stage_timings/1", "generated_by": "scripts/build_stage.py",
        "inputs": ["ledger.jsonl", "receipts/<run_id>.json",
                   "the harvest a receipt's run_dir names (exports/0001.gcode, proof/0001.3mf, setup.json), read-only"],
        "rules": {
            "leaf": "every stage line except field.<X>, which wraps locate.<X> and edit_readback.<X>; a parent is never added to its children",
            "stage_source": "receipts/<run_id>.json#stages.list (the stage lines of native_worker.log)",
            "difference": "candidate run minus the mean of the runs it is compared with (same machine, scenario and build line); K2 against K1",
            "whole_run_measure": {"guest": "host_wall", "fa706g3": "process"},
            "measures": {key: where for key, _, where in MEASURES},
            "caps": "fa706g3 and the Mac count SHADOW at most (README rule 6); the guest is the regression-evidence machine",
            "signature": "gcode_signature.py: length per (TYPE section, layer, feed) and filament per (TYPE section, layer), tolerance 0.05 mm",
        },
        "groups": groups,
        "reproducibility": reproducibility(groups, receipts),
    })
    write(evidence, "stage-timings.json", dump(data))
    write(evidence, "stage-timings.md", stage_markdown(data))
    return 0


if __name__ == "__main__":
    sys.exit(main())
