PARENT_PREFIX = "field"


def stage_values(receipt):
    """{key: seconds} of one run's stage lines, in log order.

    The key is the stage name. A name logged twice (a field located again after a scroll) keeps both
    lines: the first under its name, the next as name#2."""
    out, seen = {}, collections.Counter()
    for stage in receipt["stages"]["list"] or []:
        seen[stage["stage"]] += 1
        key = stage["stage"] if seen[stage["stage"]] == 1 else "%s#%d" % (stage["stage"], seen[stage["stage"]])
        out[key] = stage["seconds"]
    return out


def stage_label(key):
    return re.sub(r"#(\d+)$", lambda found: "（第 %s 次）" % found.group(1), key)


def kind_of(key):
    return "parent" if key.split(".")[0] == PARENT_PREFIX else "leaf"


def seconds_of(entry, receipt):
    seconds = receipt["seconds"]
    return {"process": seconds["guest"], "host_wall": seconds["host_wall"],
            "orchestration": entry.get("process_seconds"), "action": seconds["script_action"],
            "leaf_sum": receipt["stages"]["stage_sum_ok"]}


def normalised_gcode(path):
    """The export's lines with what varies from run to run without meaning removed or replaced: the
    time-stamp line, the thumbnail data, the object ids of the '; printing object' lines."""
    out, thumbnail = [], False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("; thumbnail begin"):
            thumbnail = True
        elif line.startswith("; thumbnail end"):
            thumbnail = False
        elif thumbnail:
            out.append("<thumbnail>")
        elif line.startswith("; generated by "):
            out.append("; generated by <time stamp>")
        elif line.startswith(("; printing object ", "; stop printing object ")):
            out.append(re.sub(r"id:\d+ copy \d+", "id:<n> copy <n>", line))
        else:
            out.append(line)
    return out


def saved_settings(path):
    with zipfile.ZipFile(path) as archive:
        return json.loads(archive.read("Metadata/project_settings.config").decode("utf-8-sig"))


def initial_frame(path):
    return read_json(path).get("initial_sha256")


class Exports:
    """Reads each run's export once: its normalised lines and its aggregate signature."""

    def __init__(self):
        self.lines, self.signatures = {}, {}

    def lines_of(self, run_dir):
        if run_dir.name not in self.lines:
            self.lines[run_dir.name] = normalised_gcode(run_dir / "exports" / "0001.gcode")
        return self.lines[run_dir.name]

    def signature_of(self, run_dir):
        if run_dir.name not in self.signatures:
            self.signatures[run_dir.name] = gcode_signature.signature(run_dir / "exports" / "0001.gcode")
        return self.signatures[run_dir.name]


def compare_exports(reference_dir, case_dir, exports):
    """What differs between two harvested runs: the export (line by line, then as an aggregate), the
    saved project and the first frame."""
    a, b = exports.lines_of(reference_dir), exports.lines_of(case_dir)
    first, second = saved_settings(reference_dir / "proof" / "0001.3mf"), saved_settings(case_dir / "proof" / "0001.3mf")
    frames = [initial_frame(reference_dir / "setup.json"), initial_frame(case_dir / "setup.json")]
    out = {
        "reference_run": reference_dir.name, "case_run": case_dir.name,
        "export": {"lines": [len(a), len(b)], "identical_lines": a == b,
                   "normalised_away": "the time-stamp line, the thumbnail data, the object ids of the '; printing object' lines"},
        "signature": gcode_signature.compare_signatures(exports.signature_of(reference_dir), exports.signature_of(case_dir)),
        "saved_settings": {"keys": [len(first), len(second)],
                           "differing_keys": sorted(k for k in set(first) | set(second) if first.get(k) != second.get(k))},
        "initial_frame_sha256": frames, "initial_frame_equal": frames[0] == frames[1],
    }
    # the first frame is reported, not judged: a clock or a cursor in the screenshot changes its hash
    out["behaviour_unchanged"] = out["signature"]["same"] and not out["saved_settings"]["differing_keys"]
    return out


def reproducibility(groups, receipts):
    """Per model: do the runs of the night slice the same? Every run against the earliest run of its model."""
    exports, families = Exports(), collections.OrderedDict()
    names = {"compare_276_quality": "276 立方体", "compare_276_strength": "276 立方体",
             "uia_param_overhang_speeds": "264 立方体", "uia_param_overhang_speeds_fdmt": "264 FDM 测试模型"}
    runs = sorted((dict(run, scenario=group["scenario"], machine=group["machine"])
                   for group in groups for run in group["runs"]),
                  key=lambda run: (run["started"] or "", run["run_id"]))
    for run in runs:
        families.setdefault(names[run["scenario"]], []).append(run)
    out = []
    for name, family in families.items():
        reference = family[0]
        reference_dir = Path(receipts[reference["run_id"]]["run_dir"])
        rows = []
        for run in family:
            run_dir = Path(receipts[run["run_id"]]["run_dir"])
            try:
                signature = exports.signature_of(run_dir)
                first, mine = saved_settings(reference_dir / "proof" / "0001.3mf"), saved_settings(run_dir / "proof" / "0001.3mf")
                rows.append({
                    "run_id": run["run_id"], "label": run["label"], "role": run["role"], "machine": run["machine"],
                    "commit": run["commit"], "started": run["started"],
                    "identical_lines": exports.lines_of(run_dir) == exports.lines_of(reference_dir),
                    "signature": gcode_signature.compare_signatures(exports.signature_of(reference_dir), signature),
                    "extruding_moves": signature["extruding_moves"],
                    "internal_solid_infill_moves": signature["moves_by_type"].get("Internal solid infill", 0),
                    "saved_settings_differing_keys": sorted(k for k in set(first) | set(mine) if first.get(k) != mine.get(k)),
                })
            except (OSError, KeyError, ValueError) as error:
                rows.append({"run_id": run["run_id"], "error": "%s: %s" % (type(error).__name__, error)})
        out.append({"model": name, "reference_run": reference["run_id"], "runs": rows,
                    "runs_total": len(rows),
                    "runs_same_as_reference": sum(1 for row in rows if row.get("signature", {}).get("same")),
                    "runs_identical_line_by_line": sum(1 for row in rows if row.get("identical_lines"))})
    return out


def percent(value):
    return "-" if value is None else "%.1f" % (0.0 if abs(value) < 0.05 else value)


def build_stage(ledger, receipts):
    groups = {}
    for run_id, entry in ledger.items():
        role = role_of(entry.get("label"))
        if role not in TIMED_ROLES or entry["scenario"] not in TIMED_SCENARIOS or run_id not in receipts:
            continue
        machine = receipts[run_id]["identity"]["machine"]
        groups.setdefault((entry["scenario"], machine), {}).setdefault(role, []).append((entry, receipts[run_id]))
    built = []
    order = list(TIMED_SCENARIOS)
    for scenario, machine in sorted(groups, key=lambda key: (order.index(key[0]), key[1] != "guest")):
        by_role, runs = groups[(scenario, machine)], []
        for role in ROLE_ORDER:
            for entry, receipt in sorted(by_role.get(role, []), key=lambda item: (item[0].get("started") or "", item[0]["run_id"])):
                comparison = receipt["verdicts"]["comparison"] or {}
                runs.append({
                    "role": role, "role_text": ROLE_TEXT[role], "label": entry.get("label"), "run_id": entry["run_id"],
                    "commit": receipt["identity"]["source_commit"], "started": entry.get("started"), "ended": entry.get("ended"),
                    "release_verdict": receipt["verdicts"]["release_verdict"], "verified_pass": receipt["verdicts"]["verified_pass"],
                    "comparison_status": comparison.get("status"), "business_status": comparison.get("business_status"),
                    "unmet_expectations": comparison.get("unmet_expectations"),
                    "artifact_hashes_match": receipt["artifacts"]["artifact_hashes_match"],
                    "cleanup_confirmed": receipt["verdicts"]["cleanup_confirmed"],
                    "seconds": seconds_of(entry, receipt), "stages": stage_values(receipt),
                })
        present = [run["role"] for run in runs]
        stage_ref = next((role for role in ("baseline", "timed")
                          if any(run["stages"] for run in runs if run["role"] == role)), None)
        whole_ref = next((role for role in ("baseline", "timed") if role in present), None)
        keys = []
        for run in runs:
            keys += [key for key in run["stages"] if key not in keys]
        stages = []
        for key in keys:
            row = {"stage": stage_label(key), "key": key, "kind": kind_of(key),
                   "values": {run["run_id"]: run["stages"].get(key) for run in runs}, "difference": {}}
            row["reference_mean"] = mean([run["stages"].get(key) for run in runs if run["role"] == stage_ref])
            for run in runs:
                if run["role"] in CANDIDATES:
                    against = "wait264" if run["role"] == "burst264" else stage_ref
                    base = mean([other["stages"].get(key) for other in runs if other["role"] == against])
                    value = run["stages"].get(key)
                    row["difference"][run["run_id"]] = None if value is None or base is None else value - base
            stages.append(row)
        pairs = []
        if "wait276" in present:
            pairs.append((whole_ref, "wait276", "基线 → 候选"))
        if "wait264" in present:
            pairs.append((whole_ref, "wait264", "%s → K1" % ("基线" if whole_ref == "baseline" else "计时版")))
        if "burst264" in present:
            pairs.append(("wait264", "burst264", "K1 → K2"))
            if whole_ref == "baseline":
                pairs.append(("baseline", "burst264", "基线 → K2（两步合计）"))
        if "final2" in present and whole_ref:
            pairs.append((whole_ref, "final2", "%s → 最终引擎复核" % ("基线" if whole_ref == "baseline" else "计时版")))
        links = []
        for start, end, text in pairs:
            link = {"from": start, "to": end, "text": text, "whole_run": {}}
            for measure, _, _ in MEASURES:
                a = mean([run["seconds"][measure] for run in runs if run["role"] == start])
                b = mean([run["seconds"][measure] for run in runs if run["role"] == end])
                link["whole_run"][measure] = {"from": a, "to": b, "saving": None if a is None or b is None else a - b,
                                              "percent": None if not a or b is None else (a - b) / a * 100.0}
            links.append(link)
        identity, exports = [], Exports()
        if whole_ref:
            reference = next(run for run in runs if run["role"] == whole_ref)
            for run in runs:
                if run["role"] not in CANDIDATES + ("final2", "final"):
                    continue
                try:
                    identity.append(compare_exports(Path(receipts[reference["run_id"]]["run_dir"]),
                                                    Path(receipts[run["run_id"]]["run_dir"]), exports))
                except (OSError, KeyError, ValueError, zipfile.BadZipFile) as error:
                    identity.append({"reference_run": reference["run_id"], "case_run": run["run_id"],
                                     "error": "%s: %s" % (type(error).__name__, error)})
        timed = None
        if "timed" in present and "baseline" in present:
            timed = {"baseline_action": [run["seconds"]["action"] for run in runs if run["role"] == "baseline"],
                     "timed_action": [run["seconds"]["action"] for run in runs if run["role"] == "timed"],
                     "baseline_has_stage_lines": any(run["stages"] for run in runs if run["role"] == "baseline"),
                     "timed_has_stage_lines": any(run["stages"] for run in runs if run["role"] == "timed")}
        start_state, model, chain = TIMED_SCENARIOS[scenario]
        built.append({
            "scenario": scenario, "machine": machine, "machine_text": MACHINE_TEXT[machine], "start_state": start_state,
            "model": model, "chain": list(chain), "stage_reference": stage_ref, "whole_run_reference": whole_ref,
            "builds": {run["role"]: run["commit"] for run in runs}, "runs": runs, "stages": stages, "links": links,
            "identity": identity, "timed_vs_baseline": timed,
        })
    return built


def stage_tables(group):
    """The lines of the per-stage tables of one group (leaf table, parent table, totals)."""
    runs, reference = group["runs"], [run for run in group["runs"] if run["role"] == group["stage_reference"]]
    candidates = [run for run in runs if run["role"] in CANDIDATES]
    if not candidates:
        return [], []
    two = any(run["role"] == "burst264" for run in candidates)
    first = [run for run in candidates if run["role"] == ("wait264" if two else "wait276")]
    second = [run for run in candidates if run["role"] == "burst264"]
    if two:
        head = ["叶段", "计时版" if group["stage_reference"] == "timed" else "基线", "K1 第一次", "K1 第二次",
                "K1 − 参照", "K2 第一次", "K2 第二次", "K2 − K1"]
    else:
        head = ["叶段", "基线", "候选 1", "候选 2", "差：候选 1", "差：候选 2"]
    lines = []
    difference = {}
    for run in candidates:
        against = "wait264" if run["role"] == "burst264" else group["stage_reference"]
        base = mean([other["seconds"]["leaf_sum"] for other in runs if other["role"] == against])
        value = run["seconds"]["leaf_sum"]
        difference[run["run_id"]] = None if value is None or base is None else value - base
    total_row = {"key": "@leaf_sum", "difference": difference}      # the totals row of the leaf table

    def stage_cell(run, key):
        if key == "@leaf_sum":
            return run["seconds"]["leaf_sum"]
        return run["stages"].get(key)

    def cells_of(row):
        out = [" / ".join(f3(stage_cell(run, row["key"])) for run in reference)]
        out += [f3(stage_cell(run, row["key"])) for run in first]
        out += [f3(row["difference"][run["run_id"]]) for run in first]
        if two:
            out += [f3(stage_cell(run, row["key"])) for run in second]
            out += [f3(row["difference"][run["run_id"]]) for run in second]
        return out

    for kind, title in (
        ("leaf", "**叶段**（秒）"),
        ("parent", "**父段**（`field.*`，包住 `locate.*` 和 `edit_readback.*`；只作对照，不与子段相加，不进合计）"),
    ):
        rows = [row for row in group["stages"] if row["kind"] == kind]
        if not rows:
            continue
        lines += ["", title, "", "| " + " | ".join(["父段"] + head[1:] if kind == "parent" else head) + " |",
                  "|" + "---|" * len(head)]
        for row in rows:
            lines.append("| %s | %s |" % (row["stage"].replace("|", "\\|"), " | ".join(cells_of(row))))
        if kind == "leaf":
            lines.append("| **叶段合计** | %s |" % " | ".join(cells_of(total_row)))
    return lines, head


