def shifted(text, dx=0.0, dy=0.0):
    """The file with every X/Y word of its motion lines moved, as a misplaced export looks."""
    lines = []
    for line in text.split('\n'):
        if line.startswith(('G0 ', 'G1 ', 'G2 ', 'G3 ')):
            line = XY_WORD.sub(lambda m: m.group(1) + f'{float(m.group(2)) + (dx if m.group(1) == "X" else dy):.5f}', line)
        lines.append(line)
    return '\n'.join(lines)


def project_with(folder, source, **settings):
    """A copy of a fixture project whose print settings are replaced."""
    target = folder / 'project.3mf'
    with ZipFile(source) as archive, ZipFile(target, 'w') as output:
        for info in archive.infolist():
            raw = archive.read(info.filename)
            if info.filename == 'Metadata/project_settings.config':
                raw = json.dumps(dict(json.loads(raw), **settings)).encode('utf-8')
            output.writestr(info, raw)
    return target


def only(failed, *names):
    """{check: passed} with exactly `names` failing."""
    return {check: check not in names for check in failed}


