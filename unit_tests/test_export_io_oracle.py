def test_missing_layer_leaves_a_gap_in_numbering_and_totals(tmp_path):
    text = gcode_text()
    blocks = layer_blocks(text)
    holed = write_gcode(tmp_path / 'holed.gcode', rebuild(text, blocks[:2] + blocks[3:]))
    with pytest.raises(ValueError, match="declared_layer_count: 4 layer markers but declared totals "
                                         r"\{'; total layer number': \[5\]"):
        verify_gcode_export(holed)
    assert gcode_export_facts(holed)['layer_numbers'] == [1, 2, 4, 5]
    # The same hole behind corrected totals is still a gap in the layer numbers.
    hidden = rebuild(text, blocks[:2] + blocks[3:])
    for old, new in (('TOTAL_LAYER=5', 'TOTAL_LAYER=4'), ('total layer number: 5', 'total layer number: 4'),
                     ('total layers count = 5', 'total layers count = 4')):
        hidden = hidden.replace(old, new)
    with pytest.raises(ValueError, match='layer_numbers_consecutive: 0 of 4 without a reading; layers 2->3 read 2 then 4'):
        verify_gcode_export(write_gcode(tmp_path / 'hidden.gcode', hidden))


