def test_brim_skirt_and_raft_may_leave_the_objects_only_as_far_as_the_project_allows(tmp_path):
    blocks = layer_blocks(gcode_text(box=CUBE_BOX))
    # A brim move 4.2 mm outside the cube inside its block, a skirt move 6.8 mm beyond the plate outside
    # any block, and a raft move 7.6 mm outside the cube inside the block.
    blocks[0] = blocks[0].replace(
        STOP, ';TYPE:Brim\nG1 X117.8 Y122.71 F3000\nG1 X117.8 Y149.29 E1\n' + STOP
        + ';TYPE:Skirt\nG1 X122.21 Y115.7 F3000\nG1 X148.79 Y115.7 E1\n', 1)
    blocks[1] = blocks[1].replace(
        STOP, ';TYPE:Support\nG1 X114.4 Y122.71 F3000\nG1 X114.4 Y149.29 E1\n' + STOP, 1)
    path = write_gcode(tmp_path / 'plate.gcode', rebuild(gcode_text(box=CUBE_BOX), blocks))
    worst = gcode_footprint(path, CUBE)
    assert worst['max_excursion_mm']['brim'] == pytest.approx(4.2)
    assert worst['max_excursion_mm']['skirt'] == pytest.approx(6.8)
    assert worst['max_excursion_mm']['support'] == pytest.approx(7.6) and worst['max_excursion_mm']['model'] == 0.0
    assert worst['moves']['brim'] == worst['moves']['skirt'] == worst['moves']['support'] == 1
    # The standard preset asks for no skirt and no raft: only the brim is within its allowance.
    assert only(FOOTPRINT_CHECKS, 'skirt_near_objects', 'support_on_objects') == worst['checks']
    skirt = project_with(tmp_path, CUBE, skirt_distance='5', skirt_loops='3', line_width='0.82')
    assert only(FOOTPRINT_CHECKS, 'support_on_objects') == gcode_footprint(path, skirt)['checks']
    assert gcode_footprint(path, skirt)['allowances_mm']['skirt'] == pytest.approx(8.46)
    (tmp_path / 'raft').mkdir()
    raft = project_with(tmp_path / 'raft', CUBE, skirt_distance='5', skirt_loops='3', line_width='0.82',
                        raft_layers='3', raft_first_layer_expansion='5', raft_expansion='1.5')
    assert all(gcode_footprint(path, raft)['checks'].values())
    (tmp_path / 'narrow').mkdir()
    narrow = project_with(tmp_path / 'narrow', CUBE, brim_width='1')
    assert only(FOOTPRINT_CHECKS, 'skirt_near_objects', 'support_on_objects', 'brim_near_objects') == gcode_footprint(
        path, narrow)['checks']
    # The G-code's own config block never widens an allowance.
    loud = write_gcode(tmp_path / 'loud.gcode', gcode_text(box=CUBE_BOX).replace(
        '; CONFIG_BLOCK_START\n', '; CONFIG_BLOCK_START\n; brim_width = 200\n; skirt_distance = 200\n'))
    assert gcode_footprint(loud, CUBE)['allowances_mm']['brim'] == 6.1


