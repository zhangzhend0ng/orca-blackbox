def gcode_text(layers=5, total=None, marker_numbers=True, box=None, name='立方体', purge_line=False):
    """The layout of a real Snapmaker Orca 2.4.0 / U1 export, shortened to `layers` layers.

    `box` is ((x0, x1), (y0, y1)): the square then lies half a 0.42 mm line inside it and each layer's
    moves sit in a `; printing object <name>` block, as the real export's do."""
    total = layers if total is None else total
    # The machine's purge line at the front edge of the bed, as the U1 start G-code draws it.
    purge = 'G1 X85 Y1 Z2 F18000\nG1 Z0.2\nG1 X185 E15 F360\n' if purge_line else ''
    head = f"""; HEADER_BLOCK_START
; generated by Snapmaker Orca 2.4.0 on 2026-11-25 at 23:38:56
; total layer number: {total}
; filament_density: 1.24,1.32
; max_z_height: {0.25 + 0.2 * (layers - 1):.2f}
; HEADER_BLOCK_END

; THUMBNAIL_BLOCK_START
; thumbnail begin 48x48 16
; iVBORw0KGgoAAAANSUhEUgAAADAAAAAwCAYAAABXAvmH
; thumbnail end
; THUMBNAIL_BLOCK_END

; EXECUTABLE_BLOCK_START
M73 P0 R1
M106 S0
PRINT_START
SET_PRINT_STATS_INFO TOTAL_LAYER={total} CURRENT_LAYER=0
M140 S65
M104 T0 S140
        SET_PURIFIER_MODE MODE=1 DESIRE_TEMP=42
G28 X Y
G28 Z I140 J140
M104 S0 T0 A0
M104 T0 S130
G90
G21
M83 ; use relative distances for extrusion
T0
{purge}"""
    blocks = []
    for number in range(1, layers + 1):
        z = 0.25 + 0.2 * (number - 1)
        stats = f'SET_PRINT_STATS_INFO TOTAL_LAYER={total} CURRENT_LAYER={number}\n' if marker_numbers else ''
        square = (box[0][0] + 0.21, box[0][1] - 0.21, box[1][0] + 0.21, box[1][1] - 0.21) if box else (110.0, 160.0, 110.0, 160.0)
        x0, x1, y0, y1 = square
        wrap = f'; printing object {name} id:1 copy 0\n' if box else ''
        close = f'; stop printing object {name} id:1 copy 0\n' if box else ''
        blocks.append(f""";LAYER_CHANGE
;Z:{z:.2f}
;HEIGHT:{0.25 if number == 1 else 0.2:.2f}
;BEFORE_LAYER_CHANGE
;{z:.2f}
G92 E0
TIMELAPSE_TAKE_FRAME
G1 E-1.5 F1800
;AFTER_LAYER_CHANGE
;{z:.2f}
{stats};TYPE:Inner wall
{wrap}G1 X{x0:g} Y{y0:g} F3000
G1 X{x1:g} Y{y0:g} E3.00173
G1 X{x1:g} Y{y1:g} E3.00173
G1 X{x0:g} Y{y1:g} E3.00173
G1 X{x0:g} Y{y0:g} E3.00173
{close}
""")
    tail = f"""{END};TYPE:Custom
PRINT_END
TIMELAPSE_STOP
M73 P100 R0
; EXECUTABLE_BLOCK_END

; filament used [mm] = 2546.07, 0.00, 0.00
; total layers count = {total}
; estimated printing time (normal mode) = 21m 22s

; CONFIG_BLOCK_START
; layer_height = 0.2
; machine_end_gcode = PRINT_END\\nTIMELAPSE_STOP
; CONFIG_BLOCK_END
"""
    return head + ''.join(blocks) + tail


def write_gcode(path, text):
    path.write_text(text, encoding='utf-8', newline='\n')
    return path


def rebuild(text, blocks):
    """The file with its layer blocks replaced (the start and the end G-code stay)."""
    first, last = text.index(';LAYER_CHANGE\n'), text.rindex(END)
    return text[:first] + ''.join(';LAYER_CHANGE\n' + block for block in blocks) + text[last:]


def layer_blocks(text):
    first, last = text.index(';LAYER_CHANGE\n'), text.rindex(END)
    return text[first:last].split(';LAYER_CHANGE\n')[1:]


