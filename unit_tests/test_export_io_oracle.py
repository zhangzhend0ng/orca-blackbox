@pytest.mark.parametrize('goal, kept', [((0, 0), 0), ((135, 135), 2)], ids=['origin', 'piled-up'])
def test_objects_moved_to_the_origin_or_onto_each_other_are_rejected(two_objects, goal, kept):
    project, _merged = two_objects
    moved = []
    for _name, triangles in world_triangles(project):
        xs = [vertex[axis] for triangle in triangles for vertex in triangle for axis in (0,)]
        ys = [vertex[axis] for triangle in triangles for vertex in triangle for axis in (1,)]
        shift = (goal[0] - (min(xs) + max(xs)) / 2, goal[1] - (min(ys) + max(ys)) / 2, 0.0)
        moved += [tuple(tuple(c + s for c, s in zip(vertex, shift)) for vertex in triangle) for triangle in triangles]
    shifted = write_stl(project.parent / f'moved-{goal[0]}.stl', moved)
    # Piled up, the moved cube's -X face lands on where the cube's +X face was: 2 of its 12
    # triangles coincide, the other 10 expose the move. At the origin none does.
    with pytest.raises(ValueError, match=f"only {kept} of 12 triangles of '立方体' are in the STL at their plate position"):
        verify_merged_stl(project, shifted)


